// Vendored by sdd-pipeline 0.3.2 (scripts/lib/trace-matrix.mjs) by install-git-hooks.sh; re-install overwrites it — edit the plugin, not this copy.
// trace-matrix.mjs — `sdd trace matrix [--out spec/TRACEABILITY-MATRIX.md]`: the traceability matrix, generated.
// Node >= 18, no dependencies. Library: no console output.
//
// A hand-written spec/TRACEABILITY-MATRIX.md is written once and never maintained (club, 11/2026: one commit, while
// three changes added requirements). Every link it states is already in the repository: the documents that cite each
// requirement, the FASE that delivers it, its tasks, its tests and its commits. This builds it from them, so it is
// regenerated after any change instead of edited.
import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { parseRequirements } from "../sdd-jev.mjs";

const SPEC_DEF = /(?<![A-Za-z0-9-])((?:UC|WF|API|INV|ADR|BDD|NFR|RN)-[A-Z0-9]+(?:-[A-Z0-9]+)*)(?![A-Za-z0-9])/g;
const TASK_ID = /\bTASK-F\d+-\d{3,4}\b/;

function walk(abs, acc, test, depth = 0) {
  let st;
  try { st = statSync(abs); } catch { return acc; }
  if (st.isDirectory()) {
    if (depth > 6) return acc;
    let es = [];
    try { es = readdirSync(abs).sort(); } catch { return acc; }
    for (const e of es) if (!e.startsWith(".") && e !== "node_modules") walk(path.join(abs, e), acc, test, depth + 1);
  } else if (test(abs) && st.size < 4 * 1024 * 1024) acc.push(abs);
  return acc;
}
const read = (f) => { try { return readFileSync(f, "utf8"); } catch { return ""; } };
const idRe = (id) => new RegExp(`(?<![A-Za-z0-9-])${id.replace(/[-]/g, "\\-")}(?![0-9])`);

/**
 * rows: [{ id, title, deprecated, spec[], fases[], tasks[], tests[], commits }]
 * opts: { root, requirements, testPaths (default ["tests"]), commitsFor(id) → number (optional) }
 */
export function buildMatrix({ root, requirements = "requirements/REQUIREMENTS.md", testPaths = ["tests"], commitsFor = null }) {
  const reqs = parseRequirements(read(path.resolve(root, requirements)));
  const specFiles = walk(path.join(root, "spec"), [], (f) => /\.md$/i.test(f) && !/TRACEABILITY-MATRIX\.md$/i.test(f))
    .map((f) => ({ f, t: read(f) }));
  const faseFiles = walk(path.join(root, "plan"), [], (f) => /FASE-\d+[^/]*\.md$/i.test(f)).map((f) => ({ f, t: read(f) }));
  const taskFiles = walk(path.join(root, "task"), [], (f) => /\.md$/i.test(f)).map((f) => ({ f, t: read(f) }));
  const testFiles = testPaths.flatMap((p) => walk(path.join(root, p), [], (f) => /\.(m?[jt]sx?|py|rb|go|java|kt|rs|php|feature)$/i.test(f)))
    .map((f) => ({ f, t: read(f) }));
  const rel = (f) => path.relative(root, f).split(path.sep).join("/");
  return reqs.map((r) => {
    const re = idRe(r.id);
    // Spec: the ids defined in the spec documents that cite the requirement (else the file name)
    const spec = new Set();
    for (const { f, t } of specFiles) {
      if (!re.test(t)) continue;
      const own = [...path.basename(f).matchAll(SPEC_DEF)].map((m) => m[1]);
      if (own.length) own.forEach((x) => spec.add(x)); else spec.add(rel(f));
    }
    const fases = [...new Set(faseFiles.filter(({ t }) => re.test(t)).map(({ f }) => (path.basename(f).match(/FASE-\d+/i) || [""])[0].toUpperCase()))]
      .filter(Boolean).sort((a, b) => Number(a.slice(5)) - Number(b.slice(5)));
    // Tasks: lines under a task heading (or the task line itself) that cite the requirement
    const tasks = new Set();
    for (const { t } of taskFiles) {
      let cur = null;
      for (const l of t.split("\n")) {
        const m = l.match(TASK_ID);
        if (m && /^\s*(?:#{1,6}\s|[-*]\s+\[)/.test(l)) cur = m[0];
        if (cur && re.test(l)) tasks.add(cur);
      }
    }
    const tests = testFiles.filter(({ t }) => re.test(t)).map(({ f }) => rel(f));
    return { id: r.id, title: r.title, deprecated: r.deprecated, spec: [...spec].sort(), fases, tasks: [...tasks].sort(), tests,
      commits: commitsFor ? commitsFor(r.id) : null };
  });
}

export function renderMatrix(rows) {
  const cell = (a) => (a.length ? a.join(", ") : "—");
  const o = ["# Traceability Matrix", "",
    "> Generated by `sdd trace matrix --out spec/TRACEABILITY-MATRIX.md`. Do not edit by hand: regenerate it after a change.", "",
    "| Requirement | Spec | FASE | Tasks | Tests | Commits |", "|---|---|---|---|---|---|"];
  for (const r of rows) {
    o.push(`| ${r.id}${r.deprecated ? " (deprecated)" : ""} | ${cell(r.spec)} | ${cell(r.fases)} | ${cell(r.tasks)} | ${r.tests.length ? r.tests.length + " file(s)" : "—"} | ${r.commits ?? "—"} |`);
  }
  const active = rows.filter((r) => !r.deprecated);
  const orphans = active.filter((r) => !r.spec.length && !r.fases.length);
  const untraced = active.filter((r) => !r.tests.length && !(r.commits > 0));
  o.push("", `Coverage: ${active.length - orphans.length}/${active.length} requirements specified or planned. Orphans: ${orphans.length ? orphans.map((r) => r.id).join(", ") : "none"}.`
    + ` ${active.length - untraced.length}/${active.length} with tests or commits.`);
  return o.join("\n") + "\n";
}
